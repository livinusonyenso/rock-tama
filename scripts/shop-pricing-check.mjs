import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const exports={};
vm.runInNewContext(ts.transpileModule(readFileSync('content/commerce.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,{exports,Intl,URLSearchParams});
const {variantById,selectionHref}=exports;
assert.equal(variantById('750-single').amount,650);
assert.equal(variantById('750-pack12').amount,7500);
assert.equal(variantById('1500-carton').amount,14500);
assert.equal(variantById('1500-single').amount,null);
const pack=new URL(selectionHref([{variantId:'750-pack12',quantity:2}]),'https://example.test');
assert.equal(pack.searchParams.get('quantity'),'24');assert.equal(pack.searchParams.get('unit'),'bottles');assert.equal(pack.searchParams.get('product'),'750ml-glass-bottle');
const carton=new URL(selectionHref([{variantId:'1500-carton',quantity:3}]),'https://example.test');assert.equal(carton.searchParams.get('quantity'),'3');assert.equal(carton.searchParams.get('unit'),'cartons');
const mixed=new URL(selectionHref([{variantId:'750-single',quantity:2},{variantId:'1500-carton',quantity:1}]),'https://example.test');assert.equal(mixed.searchParams.get('product'),'mixed');assert.equal(mixed.searchParams.has('quantity'),false);assert(mixed.searchParams.get('message').includes('No payment has been made'));
console.log('PASS approved draft prices, absent 1.5L price, pack-to-bottle conversion, carton units and mixed-unit quotation context.');
