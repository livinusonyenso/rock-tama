import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import vm from "node:vm";
import ts from "typescript";
const env={};
const load=(file,require)=>{const exports={};vm.runInNewContext(ts.transpileModule(readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{exports,require,process:{env}});return exports;};
const demoAuth=load('lib/demo-auth.ts');
const exports=load('lib/account/demo.ts',id=>{if(id==='@/lib/demo-auth')return demoAuth;throw new Error(`unexpected import ${id}`);});
assert.equal(exports.demoLoginEnabled(),true);
assert.equal(exports.parseDemoSession(undefined),null);
assert.equal(exports.parseDemoSession('broken'),null);
assert.equal(exports.parseDemoSession(JSON.stringify({mode:'real',email:'demo@example.com'})),null);
assert.equal(exports.parseDemoSession(JSON.stringify({mode:'demo',email:''})),null);
assert.equal(exports.parseDemoSession(JSON.stringify({mode:'demo',email:'demo@example.com'})).email,'demo@example.com');
// D-133: a production server (next start, Vercel, Docker, AWS) has no demo login unless explicitly enabled.
env.NODE_ENV='production';assert.equal(exports.demoLoginEnabled(),false);assert.equal(exports.parseDemoSession(JSON.stringify({mode:'demo',email:'demo@example.com'})),null);
env.DEMO_AUTH='enabled';assert.equal(exports.demoLoginEnabled(),true);
env.DEPLOY_MODE='production';assert.equal(exports.demoLoginEnabled(),false);assert.equal(exports.parseDemoSession(JSON.stringify({mode:'demo',email:'demo@example.com'})),null);
delete env.NODE_ENV;delete env.DEMO_AUTH;assert.equal(exports.demoLoginEnabled(),false);
console.log('PASS demo session parsing; demo login off on production servers unless DEMO_AUTH=enabled, and never with DEPLOY_MODE=production.');
